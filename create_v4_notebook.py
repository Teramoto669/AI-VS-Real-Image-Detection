                    "        f5 = F.conv2d(x, self.k5_weight, padding=2, groups=3)\n",
                    "        sh = f3[:, 1::3, :, :]\n",
                    "        sv = f3[:, 2::3, :, :]\n",
                    "        smag = torch.sqrt(sh ** 2 + sv ** 2 + 1e-6)\n",
                    "        lap3_out = f3[:, 0::3, :, :]\n",
                    "        lap5_out = f5[:, 0::2, :, :]\n",
                    "        dog_out = f5[:, 1::2, :, :]\n",
                    "        npr_out = self.npr(x)\n",
                    "        return torch.cat([lap3_out, lap5_out, dog_out, smag, npr_out], dim=1)\n",
